/**
 * Generates `src/time/cities.generated.ts` from the `city-timezones` dataset.
 *
 * The app must never invent a time zone or a coordinate, so the shipped city
 * list is derived from a real dataset at build time rather than typed by hand.
 * Three passes build it:
 *
 *   1. Every city above POP_FLOOR, so search covers the places people live.
 *   2. The largest city of every zone in the dataset, so no zone is unreachable
 *      just because its only settlements are small (Pacific/Apia, Atlantic/Azores).
 *   3. Every remaining IANA zone `Intl` knows about, as a zone-only entry.
 *      Most are aliases (Asia/Calcutta) or research bases (Antarctica/Troll).
 *      Where the zone's trailing label names a city in the dataset we inherit
 *      that city's coordinates; otherwise coordinates stay null and the UI
 *      omits sunrise/sunset for it, as the spec requires.
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath, URL as NodeURL } from 'node:url';

const require = createRequire(import.meta.url);
const { cityMapping } = require('city-timezones');

const POP_FLOOR = 150_000;
const OUT = fileURLToPath(new NodeURL('../src/time/cities.generated.ts', import.meta.url));

/** `Intl` accepts these but they are offsets, not places. */
const isPlaceZone = (zone) =>
  zone.includes('/') && !zone.startsWith('Etc/') && !zone.startsWith('SystemV/');

const isValidZone = (zone) => {
  try {
    new Intl.DateTimeFormat('en-US', { timeZone: zone });
    return true;
  } catch {
    return false;
  }
};

/** The dataset uses the sentinel `-99` where a territory has no ISO code. */
const text = (v) => (typeof v === 'string' ? v.trim() : '');

const round = (n, places) => {
  const f = 10 ** places;
  return Math.round(n * f) / f;
};

const usable = cityMapping.filter(
  (c) => c.timezone && c.city_ascii && c.country && isValidZone(c.timezone),
);

// Pass 1 + 2 ------------------------------------------------------------------
/** @type {Map<string, object>} keyed by city+province+country so homonyms survive. */
const picked = new Map();
const keyOf = (c) => `${c.city_ascii}|${c.province ?? ''}|${c.iso2}`;

for (const c of usable) {
  if ((c.pop ?? 0) >= POP_FLOOR) picked.set(keyOf(c), c);
}

const largestPerZone = new Map();
for (const c of usable) {
  const held = largestPerZone.get(c.timezone);
  if (!held || (c.pop ?? 0) > (held.pop ?? 0)) largestPerZone.set(c.timezone, c);
}
for (const c of largestPerZone.values()) picked.set(keyOf(c), c);

const rows = [...picked.values()]
  .map((c) => ({
    name: text(c.city_ascii),
    country: text(c.country),
    iso2: text(c.iso2),
    province: text(c.province),
    zone: c.timezone,
    lat: round(c.lat, 4),
    lon: round(c.lng, 4),
    pop: Math.round(c.pop ?? 0),
  }))
  .sort((a, b) => b.pop - a.pop || a.name.localeCompare(b.name));

// Pass 3 ----------------------------------------------------------------------
const covered = new Set(rows.map((r) => r.zone));
const byAsciiName = new Map();
for (const c of usable) {
  const k = c.city_ascii.trim().toLowerCase();
  const held = byAsciiName.get(k);
  if (!held || (c.pop ?? 0) > (held.pop ?? 0)) byAsciiName.set(k, c);
}

const zoneOnly = [];
for (const zone of Intl.supportedValuesOf('timeZone')) {
  if (covered.has(zone) || !isPlaceZone(zone)) continue;
  const label = (zone.split('/').pop() ?? zone).replace(/_/g, ' ');
  const twin = byAsciiName.get(label.toLowerCase());
  zoneOnly.push({
    name: label,
    country: twin ? text(twin.country) : (zone.split('/')[0] ?? '').replace(/_/g, ' '),
    iso2: twin ? text(twin.iso2) : '',
    province: '',
    zone,
    lat: twin ? round(twin.lat, 4) : null,
    lon: twin ? round(twin.lng, 4) : null,
    pop: 0,
  });
}
zoneOnly.sort((a, b) => a.zone.localeCompare(b.zone));

const all = [...rows, ...zoneOnly];
const num = (n) => (n === null ? 'null' : String(n));
const str = (s) => JSON.stringify(s);

const body = all
  .map((r) => `  [${str(r.name)},${str(r.country)},${str(r.iso2)},${str(r.province)},${str(r.zone)},${num(r.lat)},${num(r.lon)},${r.pop}],`)
  .join('\n');

writeFileSync(
  OUT,
  `// Generated by scripts/build-cities.mjs from the \`city-timezones\` dataset.
// Do not edit by hand; run \`npm run build:cities\` instead.
// Shape: [name, country, iso2, province, ianaZone, lat, lon, population]
// \`lat\`/\`lon\` are null where the dataset has no coordinates for the zone.

export type RawCity = readonly [
  name: string,
  country: string,
  iso2: string,
  province: string,
  zone: string,
  lat: number | null,
  lon: number | null,
  population: number,
];

export const RAW_CITIES: readonly RawCity[] = [
${body}
];
`,
  'utf8',
);

const withCoords = all.filter((r) => r.lat !== null).length;
console.log(
  `wrote ${all.length} entries (${rows.length} cities, ${zoneOnly.length} zone-only, ` +
    `${withCoords} with coordinates) covering ${new Set(all.map((r) => r.zone)).size} zones`,
);
