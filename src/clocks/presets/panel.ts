type Shape = Omit<PanelSpec, 'family'>;

function panel(
  id: string,
  name: string,
  tags: readonly string[],
  palette: FacePalette,
  shape: Shape,
  naturalDark?: boolean,
): ClockPreset {
  return {
    id,
    name,
    family: 'panel',
    kind: 'digital',
    tags,
    palette,
    ...(naturalDark === undefined ? {} : { naturalDark }),
    spec: { family: 'panel', ...shape },
  };
}

