// -------------------------------------------------------------------- flip --

function flip(
  id: string,
  name: string,
  tags: readonly string[],
  palette: FacePalette,
  shape: Omit<FlipSpec, 'family'>,
  naturalDark?: boolean,
): ClockPreset {
  return {
    id,
    name,
    family: 'flip',
    kind: 'digital',
    tags,
    palette,
    ...(naturalDark === undefined ? {} : { naturalDark }),
    spec: { family: 'flip', ...shape },
  };
}

